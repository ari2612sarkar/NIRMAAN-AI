"""Rule-based AI Copilot.

No external LLM call — intentionally. Every answer is generated by
matching the question to one of a small set of grounded "tools" (plain
Python functions over the same services/calc layer the rest of the app
uses) and filling a template with their real output. This guarantees the
copilot can never hallucinate a number: it either has a tool that
answers the question, or it says so.
"""
from __future__ import annotations

from fastapi import APIRouter, Depends
from pydantic import BaseModel
from sqlalchemy.orm import Session

from .. import models as m
from .. import services
from ..calc import SimulationInputs, apply_simulation
from ..core import get_db
from ..ml.maintenance import score_vehicle
from ..recommendations import top_recommendations

router = APIRouter(prefix="/api/copilot", tags=["copilot"])


class AskRequest(BaseModel):
    question: str


def _tool_cost_summary(db: Session) -> str:
    baseline = services.compute_baseline_metrics(db, window_days=30)
    result = apply_simulation(baseline, SimulationInputs())
    breakdown = result["cost_breakdown"]
    return (
        f"Total operating cost over the last 30 days is ₹{result['total_operating_cost']:,.0f}: "
        f"₹{breakdown['collection']:,.0f} collection, ₹{breakdown['disposal']['net_cost']:,.0f} disposal, "
        f"₹{breakdown['maintenance']['total']:,.0f} maintenance, ₹{breakdown['overflow']:,.0f} overflow penalties."
    )


def _tool_zone_priority(db: Session) -> str:
    zones = services.zone_summaries(db)
    if not zones:
        return "No zone data available yet."
    worst = max(zones, key=lambda z: z["total_waste_kg_30d"])
    return (
        f"{worst['name']} should be prioritized: it generated {worst['total_waste_kg_30d']:,.0f} kg "
        f"over the last 30 days with only {worst['segregation_pct']:.0f}% segregation."
    )


def _tool_maintenance_priority(db: Session) -> str:
    vehicles = db.query(m.Vehicle).all()
    if not vehicles:
        return "No vehicle data available yet."
    fleet_avg = sum(v.odometer_km for v in vehicles) / len(vehicles)
    scored = []
    for v in vehicles:
        records = db.query(m.MaintenanceRecord).filter(m.MaintenanceRecord.vehicle_id == v.id).all()
        rd = [{"date": r.date, "event_type": r.event_type, "cost": r.cost, "downtime_hours": r.downtime_hours} for r in records]
        import datetime as dt
        s = score_vehicle({"vehicle_code": v.vehicle_code, "odometer_km": v.odometer_km}, rd, fleet_avg, dt.date.today())
        scored.append(s)
    scored.sort(key=lambda s: s["risk_score"], reverse=True)
    top = scored[0]
    return (
        f"{top['vehicle_code']} has the highest maintenance risk ({top['risk_score']:.0f}/100, {top['risk_level']}): "
        f"{', '.join(top['drivers'])}. Recommended action: {top['recommended_action']}."
    )


def _tool_recommendations(db: Session) -> str:
    recs = top_recommendations(db, limit=3)
    if not recs:
        return "No interventions are currently recommended."
    lines = [f"{r['title']} (impact score {r['impact_score']}, est. ₹{r['expected_monthly_saving']:,.0f}/month saving)" for r in recs]
    return "Top recommended interventions: " + "; ".join(lines) + "."


def _tool_simulate_segregation(db: Session, pct: float) -> str:
    baseline = services.compute_baseline_metrics(db, window_days=30)
    base_result = apply_simulation(baseline, SimulationInputs())
    sim_result = apply_simulation(baseline, SimulationInputs(segregation_adoption_pct=pct))
    saving = base_result["total_operating_cost"] - sim_result["total_operating_cost"]
    return (
        f"At {pct:.0f}% segregation adoption: mixed waste would fall from {baseline['mixed_kg']:,.0f} kg "
        f"to {sim_result['mixed_kg']:,.0f} kg, saving an estimated ₹{saving:,.0f}/month "
        f"(projected ₹{saving * 12:,.0f}/year)."
    )


@router.post("/ask")
def ask(req: AskRequest, db: Session = Depends(get_db)):
    q = req.question.lower()
    import re

    pct_match = re.search(r"(\d+(?:\.\d+)?)\s*%", q)

    if "segregat" in q and ("what" in q or "happen" in q or "if" in q):
        pct = float(pct_match.group(1)) if pct_match else 50.0
        answer = _tool_simulate_segregation(db, pct)
        tool = "run_scenario(segregation_adoption_pct)"
    elif "cost" in q and ("why" in q or "increase" in q or "breakdown" in q or "summary" in q):
        answer = _tool_cost_summary(db)
        tool = "calculate_cost_savings()"
    elif "zone" in q and ("priorit" in q or "target" in q or "first" in q):
        answer = _tool_zone_priority(db)
        tool = "get_zone_statistics()"
    elif "maintenance" in q or "vehicle" in q or "asset" in q:
        answer = _tool_maintenance_priority(db)
        tool = "get_maintenance_risk()"
    elif "recommend" in q or "intervention" in q or "save" in q or "reduce" in q:
        answer = _tool_recommendations(db)
        tool = "recommend_interventions()"
    else:
        answer = (
            "I can answer grounded questions about: operating cost breakdown, which zone to "
            "prioritize, maintenance risk/priority, recommended interventions, or 'what if segregation "
            "increased to X%?' scenarios. Try rephrasing with one of those topics."
        )
        tool = "none_matched"

    return {"question": req.question, "answer": answer, "tool_used": tool}
